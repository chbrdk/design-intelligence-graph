def existing_hosts() -> set[str]:
    hosts: set[str] = set()
    for path in EXISTING:
        data = json.loads(path.read_text())
        for entry in data.get("entries", []):
            hosts.add(host_key(entry["url"]))
    return hosts


def main() -> None:
    skip = existing_hosts()
    entries = []
    seen_ids: set[str] = set()
    seen_hosts: set[str] = set()
    for name, group, country, url in ROWS:
        key = host_key(url)
        ident = slug(name)
        if not ident or ident in seen_ids or key in seen_hosts or key in skip:
            continue
        if not url.startswith("https://"):
            continue
        seen_ids.add(ident)
        seen_hosts.add(key)
        entries.append(
            {
                "rank": len(entries) + 1,
                "id": ident,
                "name": name,
                "group": group,
                "country": country,
                "url": url,
            }
        )
        if len(entries) == 1000:
            break
    if len(entries) != 1000:
        raise SystemExit(f"expected 1000 unique entries, got {len(entries)} (skipped {len(ROWS) - len(entries)} dups/existing)")
    catalog = {
        "id": "engineering-manufacturing-1000",
        "title": "1000 worldwide engineering and manufacturing public homepages",
        "source": "Curated 2026 mix of industrial automation, machinery, EPC, aerospace, chemicals, metals, semiconductors, auto suppliers, medical devices, building materials, energy equipment, and related engineering firms. Excludes automotive-oem-50 and cross-industry-100 hosts.",
        "sourceUrl": "https://en.wikipedia.org/wiki/List_of_largest_manufacturing_companies_by_revenue",
        "year": 2026,
        "updated": "2026-08-17",
        "entries": entries,
    }
    OUT.write_text(json.dumps(catalog, indent=2) + "\n")
    print(f"wrote {OUT} ({len(entries)} entries)")


