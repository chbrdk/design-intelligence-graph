def country_iso(country: str, url: str) -> str:
    key = (country or "").strip().lower()
    if key in COUNTRY_ISO:
        return COUNTRY_ISO[key]
    host = (urlparse(url).hostname or "").lower().removeprefix("www.")
    parts = host.split(".")
    for n in (3, 2, 1):
        if len(parts) >= n:
            tld = ".".join(parts[-n:])
            if tld in TLD_ISO:
                return TLD_ISO[tld]
    return "XX"


