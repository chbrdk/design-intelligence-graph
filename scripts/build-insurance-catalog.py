def existing_hosts() -> set[str]:
    hosts: set[str] = set()
    for path in EXISTING:
        data = json.loads(path.read_text())
        for entry in data.get("entries", []):
            hosts.add(host_key(entry["url"]))
    return hosts


def source_rows() -> list[tuple[str, str, str, str]]:
    data = json.loads(SOURCE.read_text())
    rows: list[tuple[str, str, str, str]] = []
    for entry in data.get("entries", []):
        name = str(entry.get("name") or "").strip()
        url = str(entry.get("url") or "").strip()
        country = country_iso(str(entry.get("country") or ""), url)
        if not name or not url.startswith("https://"):
            continue
        rows.append((name, infer_group(name, url), country, url))
    return rows


def main() -> None:
    skip = existing_hosts()
    entries = []
    seen_ids: set[str] = set()
    seen_hosts: set[str] = set()
    for name, group, country, url in [*CURATED, *source_rows()]:
        key = host_key(url)
        ident = slug(name)
        if not ident or ident in seen_ids or key in seen_hosts or key in skip:
            continue
        if not url.startswith("https://"):
            continue
        host = key.split("/")[0]
        if host.endswith(".gov") or host.endswith(".edu"):
            continue
        seen_ids.add(ident)
        seen_hosts.add(key)
        entries.append(
            {
                "rank": len(entries) + 1,
                "id": ident,
                "name": name,
                "group": group,
                "country": country,
                "url": url,
            }
        )
        if len(entries) == 1000:
            break
    if len(entries) != 1000:
        raise SystemExit(f"expected 1000 unique entries, got {len(entries)}")
    catalog = {
        "id": "insurance-1000",
        "title": "1000 worldwide insurance, reinsurance, broker, health, and insurtech public homepages",
        "source": "Curated 2026 mix of life, P&C, health, reinsurance, brokers, mutuals, takaful, and insurtech. Majors first, then Wikidata/Wikipedia official websites. Excludes hosts already in automotive-oem-50, cross-industry-100, and engineering-manufacturing-1000.",
        "sourceUrl": "https://en.wikipedia.org/wiki/List_of_largest_insurance_companies",
        "year": 2026,
        "updated": "2026-08-18",
        "entries": entries,
    }
    OUT.write_text(json.dumps(catalog, indent=2) + "\n")
    groups = sorted({e["group"] for e in entries})
    print(f"wrote {OUT} ({len(entries)} entries, {len(groups)} groups)")
    print("groups:", ", ".join(groups))


if __name__ == "__main__":
    main()
